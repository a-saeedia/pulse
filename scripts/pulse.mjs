#!/usr/bin/env node
/**
 * Daily pulse.
 *
 * Rewrites the block between PULSE markers in README.md and appends one row to
 * data/history.csv. Runs from GitHub Actions with the repo's GITHUB_TOKEN, but
 * commits as the account owner's noreply address so the contribution counts.
 */

const TOKEN = process.env.GITHUB_TOKEN;
if (!TOKEN) {
  console.error('GITHUB_TOKEN is required');
  process.exit(1);
}

const API = 'https://api.github.com/graphql';
const LOGIN = 'a-saeedia';

const query = `
query($login: String!) {
  user(login: $login) {
    contributionsCollection {
      contributionCalendar {
        totalContributions
        weeks {
          contributionDays { date contributionCount }
        }
      }
    }
    repositories(first: 100, privacy: PUBLIC, orderBy: {field: PUSHED_AT, direction: DESC}) {
      totalCount
      nodes { stargazerCount }
    }
    followers { totalCount }
  }
}`;

const res = await fetch(API, {
  method: 'POST',
  headers: {
    Authorization: `Bearer ${TOKEN}`,
    'User-Agent': 'pulse',
    'Content-Type': 'application/json',
  },
  body: JSON.stringify({ query, variables: { login: LOGIN } }),
});

if (!res.ok) {
  console.error('graphql failed', res.status, (await res.text()).slice(0, 300));
  process.exit(1);
}

const payload = await res.json();
if (payload.errors) {
  console.error('graphql errors', JSON.stringify(payload.errors).slice(0, 400));
  process.exit(1);
}

const user = payload.data.user;
const calendar = user.contributionsCollection.contributionCalendar;
const days = calendar.weeks
  .flatMap((w) => w.contributionDays)
  .sort((a, b) => a.date.localeCompare(b.date));

const totalContributions = calendar.totalContributions;
const stars = user.repositories.nodes.reduce((sum, r) => sum + r.stargazerCount, 0);
const repos = user.repositories.totalCount;
const followers = user.followers.totalCount;

// Streak: today counts if it already has activity, otherwise the streak is
// measured up to yesterday (the day is not lost until it ends).
const today = new Date().toISOString().slice(0, 10);
const byDate = new Map(days.map((d) => [d.date, d.contributionCount]));

let streak = 0;
const cursor = new Date(`${today}T00:00:00Z`);
if ((byDate.get(today) ?? 0) === 0) cursor.setUTCDate(cursor.getUTCDate() - 1);
for (;;) {
  const key = cursor.toISOString().slice(0, 10);
  if ((byDate.get(key) ?? 0) > 0) {
    streak++;
    cursor.setUTCDate(cursor.getUTCDate() - 1);
  } else break;
}

let longest = 0;
let run = 0;
for (const d of days) {
  if (d.contributionCount > 0) {
    run++;
    longest = Math.max(longest, run);
  } else run = 0;
}
longest = Math.max(longest, streak);

const fs = await import('node:fs/promises');

const START = '<!-- PULSE:START -->';
const END = '<!-- PULSE:END -->';
const block = `${START}
| metric | value |
|---|---|
| contributions (last year) | ${totalContributions} |
| current streak | ${streak} day${streak === 1 ? '' : 's'} |
| longest streak | ${longest} days |
| public repos | ${repos} |
| stars across public repos | ${stars} |
| followers | ${followers} |

<sub>updated ${new Date().toISOString().replace('T', ' ').slice(0, 19)} UTC — generated by \`.github/workflows/pulse.yml\`</sub>
${END}`;

const readme = await fs.readFile('README.md', 'utf8');
const next = readme.includes(START)
  ? readme.replace(new RegExp(`${START}[\\s\\S]*?${END}`), block)
  : `${readme.trimEnd()}\n\n${block}\n`;

await fs.mkdir('data', { recursive: true });
await fs.writeFile('README.md', next);

const header = 'date,total_contributions,streak,longest_streak,repos,stars,followers';
let csv = header + '\n';
try {
  csv = await fs.readFile('data/history.csv', 'utf8');
} catch { /* first run */ }
const rows = csv.trimEnd().split('\n').filter((l) => l && !l.startsWith('date,'));
rows.push([today, totalContributions, streak, longest, repos, stars, followers].join(','));
await fs.writeFile('data/history.csv', header + '\n' + rows.join('\n') + '\n');

console.log(`pulse ok — streak ${streak}, longest ${longest}, total ${totalContributions}`);
